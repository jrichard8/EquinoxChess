"""Fit tapered piece-square corrections on historical positions (no games from the new loop)."""
import argparse
import csv
import hashlib
import json
from pathlib import Path
import re
import subprocess

import chess
import chess.pgn
import numpy as np

ROOT = Path(__file__).resolve().parents[4]
PHASE = (0, 1, 1, 2, 4, 0)
RIDGE = 32.0


def samples():
    seen = set()
    for suite in ("v1", "v2"):
        fixture = json.loads((ROOT / "tools/tactics" / suite / "positions.json").read_text())
        for value in fixture.values():
            if isinstance(value, list):
                seen.update(chess.Board(r["fen"]).epd() for r in value if isinstance(r, dict) and "fen" in r)
    with (ROOT / "tools/kingzone/canaries.csv").open() as stream:
        seen.update(chess.Board(r["fen"]).epd() for r in csv.DictReader(stream))
    for path in sorted((ROOT / "matches/elo1850").glob("*.pgn")):
        with path.open() as stream:
            while (game := chess.pgn.read_game(stream)) is not None:
                if game.errors:
                    raise ValueError(game.headers)
                b = game.board()
                group = int.from_bytes(hashlib.sha256(b.epd().encode()).digest()[:4], "big")
                for ply, m in enumerate(game.mainline_moves(), 1):
                    b.push(m)
                    if ply < 6 or (ply + group) % 4 or b.is_check() or b.is_game_over():
                        continue
                    key = b.epd()
                    if key not in seen:
                        seen.add(key)
                        yield b.fen(), group % 8 == 0


def teach(engine, fens):
    pattern = re.compile(r"Final evaluation\s+([+-]?\d+\.\d+) \(white side\)")
    with subprocess.Popen([engine], stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True) as sf:
        values = []
        try:
            for fen in fens:
                sf.stdin.write(f"position fen {fen}\neval\nisready\n")
                sf.stdin.flush()
                score = None
                for line in sf.stdout:
                    if match := pattern.search(line):
                        score = round(100 * float(match[1]))
                    if line.strip() == "readyok":
                        break
                if score is None:
                    raise ValueError(f"Missing static evaluation for {fen}")
                values.append(score)
        finally:
            sf.stdin.write("quit\n")
            sf.stdin.flush()
    return np.asarray(values)


def features(fens):
    x = np.zeros((len(fens), 768), dtype=np.float32)
    for row, fen in enumerate(fens):
        b = chess.Board(fen)
        phase = min(24, sum(PHASE[p.piece_type-1] for p in b.piece_map().values())) / 24
        for sq, piece in b.piece_map().items():
            sign = 1 if piece.color else -1
            col = (piece.piece_type-1)*64 + (sq if piece.color else chess.square_mirror(sq))
            x[row, col] += sign * phase
            x[row, col + 384] += sign * (1-phase)
    return x


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("stockfish", type=Path)
    parser.add_argument("base_static", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    fens, validation = zip(*samples())
    old = np.asarray(list(map(int, subprocess.check_output([args.base_static], input="\n".join(fens)+"\n", text=True).split())))
    labels = teach(args.stockfish, fens)
    x = features(fens)
    # Downweight gross tactical outliers that additive square terms cannot explain.
    mask = ~np.array(validation)
    train = x[mask].astype(np.float64)
    residual = np.clip((labels-old)[mask], -400, 400)
    gram = train.T @ train
    gram.flat[::len(gram)+1] += RIDGE
    w = np.rint(np.linalg.solve(gram, train.T @ residual)).astype(int)
    valid = ~mask
    print(json.dumps(dict(train=int(mask.sum()), validation=int(valid.sum()), ridge=RIDGE,
                          before=float(np.abs(labels-old)[valid].mean()),
                          after=float(np.abs(labels-old-x@w)[valid].mean()),
                          stockfish_sha256=hashlib.sha256(args.stockfish.read_bytes()).hexdigest(),
                          positions_sha256=hashlib.sha256("\n".join(fens).encode()).hexdigest())))
    with args.output.open("x") as stream:
        stream.write("// Code generated by tools/elo/2200/loop/fit_tables.py; DO NOT EDIT.\npackage search\n\n")
        for name, table in zip(("openingCorrection", "endingCorrection"), w.reshape(2, 6, 8, 8)):
            stream.write(f"var {name} = [6][64]int{{\n")
            for piece in table:
                stream.write("{\n")
                for rank in piece:
                    stream.write(", ".join(map(str, rank))+",\n")
                stream.write("},\n")
            stream.write("}\n")


if __name__ == "__main__":
    main()
